-- Production TAC -> phone mapping for the existing Supabase catalog.
-- SAFE BY DESIGN:
--   * never invents TACs
--   * only maps currently-unmapped rows
--   * requires a unique canonical phone candidate
--   * exact normalized model matches only
--   * brand must agree with the canonical phone brand
--   * leaves ambiguous/unresolved rows untouched
-- Result-page/UI files are not involved.

BEGIN;

-- Normalization helper used only for identity matching.
CREATE OR REPLACE FUNCTION public.normalize_device_identity(value text)
RETURNS text
LANGUAGE sql
IMMUTABLE
PARALLEL SAFE
AS $$
  SELECT trim(regexp_replace(lower(coalesce(value, '')), '[^a-z0-9]+', ' ', 'g'));
$$;

-- Indexes for the existing 254k-row TAC table and canonical phone catalog.
CREATE INDEX IF NOT EXISTS idx_tac_allocations_phone_id
  ON public.tac_allocations(phone_id);
CREATE INDEX IF NOT EXISTS idx_tac_allocations_brand_id
  ON public.tac_allocations(brand_id);
CREATE INDEX IF NOT EXISTS idx_tac_allocations_reported_brand_norm
  ON public.tac_allocations(public.normalize_device_identity(reported_brand));
CREATE INDEX IF NOT EXISTS idx_tac_allocations_reported_model_norm
  ON public.tac_allocations(public.normalize_device_identity(reported_model_name));
CREATE INDEX IF NOT EXISTS idx_phones_brand_model_norm
  ON public.phones(brand_id, public.normalize_device_identity(model_name));
CREATE INDEX IF NOT EXISTS idx_brands_name_norm
  ON public.brands(public.normalize_device_identity(name));

-- Audit table makes every automatic mapping reversible/auditable.
CREATE TABLE IF NOT EXISTS public.tac_mapping_audit (
  audit_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tac_id bigint NOT NULL,
  tac varchar NOT NULL,
  old_phone_id integer,
  new_phone_id integer NOT NULL,
  old_brand_id integer,
  new_brand_id integer NOT NULL,
  mapping_method text NOT NULL,
  previous_status text,
  previous_confidence numeric,
  mapped_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (tac_id, new_phone_id, mapping_method)
);

