-- Resolve reported brand to one and only one canonical brand.
CREATE TEMP TABLE _brand_candidates ON COMMIT DROP AS
SELECT
  t.tac_id,
  min(b.brand_id) AS brand_id,
  count(DISTINCT b.brand_id) AS candidate_count
FROM public.tac_allocations t
JOIN _brand_alias a
  ON a.alias_norm = public.normalize_device_identity(t.reported_brand)
JOIN public.brands b
  ON public.normalize_device_identity(b.name) = a.canonical_norm
WHERE t.phone_id IS NULL
GROUP BY t.tac_id;
CREATE INDEX ON _brand_candidates(tac_id);

-- Fill brand_id only when the alias resolves uniquely.
UPDATE public.tac_allocations t
SET brand_id = bc.brand_id,
    updated_at = now()
FROM _brand_candidates bc
WHERE t.tac_id = bc.tac_id
  AND t.brand_id IS NULL
  AND bc.candidate_count = 1;

-- Exact normalized model match within the resolved canonical brand.
-- Important: candidate_count must equal 1; duplicate/ambiguous catalog names are skipped.
CREATE TEMP TABLE _exact_candidates ON COMMIT DROP AS
SELECT
  t.tac_id,
  min(p.phone_id) AS phone_id,
  min(p.brand_id) AS brand_id,
  count(DISTINCT p.phone_id) AS candidate_count
FROM public.tac_allocations t
JOIN public.phones p
  ON p.brand_id = t.brand_id
 AND public.normalize_device_identity(p.model_name) = public.normalize_device_identity(t.reported_model_name)
WHERE t.phone_id IS NULL
  AND t.brand_id IS NOT NULL
  AND nullif(public.normalize_device_identity(t.reported_model_name), '') IS NOT NULL
GROUP BY t.tac_id;
CREATE INDEX ON _exact_candidates(tac_id);

INSERT INTO public.tac_mapping_audit
  (tac_id, tac, old_phone_id, new_phone_id, old_brand_id, new_brand_id,
   mapping_method, previous_status, previous_confidence)
SELECT
  t.tac_id, t.tac, t.phone_id, c.phone_id, t.brand_id, c.brand_id,
  'exact_normalized_brand_model', t.match_status, t.match_confidence
FROM public.tac_allocations t
JOIN _exact_candidates c ON c.tac_id = t.tac_id
WHERE t.phone_id IS NULL
  AND c.candidate_count = 1
ON CONFLICT DO NOTHING;

UPDATE public.tac_allocations t
SET phone_id = c.phone_id,
    brand_id = c.brand_id,
    match_status = 'matched',
    match_confidence = GREATEST(coalesce(t.match_confidence, 0), 0.95),
    updated_at = now()
FROM _exact_candidates c
WHERE t.tac_id = c.tac_id
  AND t.phone_id IS NULL
  AND c.candidate_count = 1;

-- Mark obviously impossible extracted years as NULL. This avoids values such as 2033/2041
-- being presented as release years. Valid historical/future-near values are left untouched.
UPDATE public.tac_allocations
SET reported_year = NULL,
    updated_at = now()
WHERE reported_year IS NOT NULL
  AND (reported_year < 1980 OR reported_year > extract(year FROM CURRENT_DATE)::int + 1);

COMMIT;

-- POST-RUN REPORT (returned by the SQL editor)
SELECT
  count(*) AS total_tacs,
  count(*) FILTER (WHERE phone_id IS NOT NULL) AS mapped_tacs,
  count(*) FILTER (WHERE phone_id IS NULL) AS unmapped_tacs,
  round(100.0 * count(*) FILTER (WHERE phone_id IS NOT NULL) / nullif(count(*),0), 2) AS mapped_percent,
  count(*) FILTER (WHERE match_status = 'matched') AS matched_status_rows
FROM public.tac_allocations;

SELECT mapping_method, count(*) AS newly_mapped
FROM public.tac_mapping_audit
GROUP BY mapping_method
ORDER BY newly_mapped DESC;
